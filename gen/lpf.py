#!/usr/bin/env python3
"""Write the pin constraints from build/fpga_pins.json:

  gateware/ecp5_2adc_2dac.lpf          for yosys/nextpnr-ecp5 (bare Verilog)
  gateware/litex/ecp5_2adc_2dac.py     a litex-boards style platform file

Both are PRODUCTS of gen/fpga.py.  Nothing in them is typed by hand, so the
schematic, the board and the gateware cannot disagree about a ball.
"""
import json, os, re, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
PINS = os.path.join(ROOT, "build", "fpga_pins.json")

IOSTD = "LVCMOS33"


def groups(assign):
    """Collapse SIGNAL<n> names into vectors: {'ADC_A_D': ['B2', 'C2', ...]}"""
    vec = collections.defaultdict(dict)
    single = {}
    for s, b in assign.items():
        m = re.match(r"^(.*?)(\d+)$", s)
        if m and not s.startswith(("CFG", "LED", "BTN")) and m.group(1) not in ("CLK_SI",):
            vec[m.group(1)][int(m.group(2))] = b
        else:
            single[s] = b
    out = {}
    for k, d in vec.items():
        out[k] = [d[i] for i in range(len(d))] if sorted(d) == list(range(len(d))) else None
        if out[k] is None:
            for i, b in d.items():
                single["%s%d" % (k, i)] = b
            del out[k]
    return out, single


def write_lpf(j, path):
    a = j["assign"]
    vec, single = groups(a)
    L = ["# %s pin constraints -- GENERATED by gen/lpf.py from build/fpga_pins.json" % j["part"],
         "# Do not edit; change gen/fpga.py and rebuild.", "",
         "BLOCK RESETPATHS;", "BLOCK ASYNCPATHS;", ""]
    clocks = {"clk_tcxo": 25.0, "clk_ext": 10.0, "clk_si0": 25.0, "clk_si1": 25.0, "clk_si2": 25.0, "eth_rxc": 125.0}
    for s, b in sorted(single.items()):
        n = s.lower()
        L.append('LOCATE COMP "%s" SITE "%s";' % (n, b))
        extra = ""
        if n in ("usb_dp", "usb_dn", "sd_cmd", "sd_d0", "sd_d1", "sd_d2", "sd_d3", "i2c_sda", "i2c_scl", "eth_mdio"):
            extra = " PULLMODE=UP"
        L.append('IOBUF PORT "%s" IO_TYPE=%s%s;' % (n, IOSTD, extra))
    for k, balls in sorted(vec.items()):
        n = k.lower().rstrip("_")
        for i, b in enumerate(balls):
            L.append('LOCATE COMP "%s[%d]" SITE "%s";' % (n, i, b))
            L.append('IOBUF PORT "%s[%d]" IO_TYPE=%s;' % (n, i, IOSTD))
    L.append("")
    for n, f in clocks.items():
        if n in [s.lower() for s in single]:
            L.append('FREQUENCY PORT "%s" %.3f MHZ;' % (n, f))
    open(path, "w").write("\n".join(L) + "\n")
    return len(single) + sum(len(v) for v in vec.values())


