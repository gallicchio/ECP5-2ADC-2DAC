#!/usr/bin/env python3
"""The 3D bodies KiCad's libraries name but do not ship, as meshes written to
library/ours.3dshapes/*.wrl (what the 3D viewer draws).  KiCad's VRML reader
takes IndexedFaceSet geometry (not the Box/Cylinder primitives), so every body
is a list of boxes and cylinders turned into triangles here.  Dimensions from
the datasheets; a model can only disagree with its land pattern about height.
Everything in mm; VRML is written in 0.1 inch, KiCad's convention."""
import os, math

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "library", "ours.3dshapes")
U = 2.54
TIN = (0.78, 0.78, 0.80); EPOXY = (0.14, 0.14, 0.15); BRASS = (0.80, 0.70, 0.40); CERAMIC = (0.82, 0.80, 0.72)
PTFE = (0.95, 0.95, 0.92)


def box(x0, y0, z0, x1, y1, z1, c):
    return ("box", (min(x0, x1), min(y0, y1), min(z0, z1), max(x0, x1), max(y0, y1), max(z0, z1)), c)


def cyl(x, y, z, r, length, c, axis="z"):
    """A cylinder of radius r from (x, y, z) along +axis ('z', 'y', '-y', 'x', '-x') for `length`."""
    return ("cyl", (x, y, z, r, length, axis), c)


MODELS = {
    # Fuse_1812_4532Metric: a 4.5 x 3.2 polyfuse, 0.9 mm tall, tinned ends
    "Fuse_1812_4532Metric": [box(-2.25, -1.6, 0, 2.25, 1.6, 0.9, CERAMIC), box(-2.3, -1.65, 0, -1.6, 1.65, 0.95, TIN), box(1.6, -1.65, 0, 2.3, 1.65, 0.95, TIN)],
    # DFN-8 2x2 mm, 0.75 tall (LM27761)
    "DFN-8-1EP_2x2mm_P0.5mm_EP0.9x1.6mm": [box(-1.0, -1.0, 0, 1.0, 1.0, 0.75, EPOXY)],
    # BAT Wireless BWSMA-KWE-Z001 edge-launch SMA: the body clamps the board
    # edge (origin at the centre pin, legs at y = 0..4.2), the barrel hangs
    # off the board along -y
    "SMA_BAT_Wireless_BWSMA-KWE-Z001": [box(-3.2, -4.2, -1.7, 3.2, 1.0, 1.7 + 1.6, BRASS),
                                        cyl(0.0, 1.0, 1.6, 3.1, 11.0, BRASS, axis="y"),
                                        cyl(0.0, 12.0, 1.6, 0.65, 1.2, TIN, axis="y"),
                                        cyl(0.0, 1.0, 1.6, 2.0, 11.1, PTFE, axis="y")],
    # (VRML y points to the TOP of the board, the opposite of KiCad's canvas y;
    #  the connector's legs sit on the board at canvas y 0..4.2, the barrel hangs off along canvas -y)
}


def _mesh_box(g):
    x0, y0, z0, x1, y1, z1 = g
    v = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0), (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
    f = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4), (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
    return v, f


def _mesh_cyl(g, n=24):
    x, y, z, r, L, axis = g
    sign = -1.0 if axis.startswith("-") else 1.0
    a = axis[-1]
    ring0, ring1 = [], []
    for i in range(n):
        t = 2 * math.pi * i / n
        u, w = r * math.cos(t), r * math.sin(t)
        if a == "z":
            p0 = (x + u, y + w, z); p1 = (x + u, y + w, z + sign * L)
        elif a == "y":
            p0 = (x + u, y, z + w); p1 = (x + u, y + sign * L, z + w)
        else:
            p0 = (x, y + u, z + w); p1 = (x + sign * L, y + u, z + w)
        ring0.append(p0); ring1.append(p1)
    v = ring0 + ring1
    c0, c1 = len(v), len(v) + 1
    v.append({"z": (x, y, z), "y": (x, y, z), "x": (x, y, z)}[a])
    v.append({"z": (x, y, z + sign * L), "y": (x, y + sign * L, z), "x": (x + sign * L, y, z)}[a])
    f = []
    for i in range(n):
        j = (i + 1) % n
        f += [(i, j, n + j), (i, n + j, n + i), (c0, j, i), (c1, n + i, n + j)]
    return v, f


def wrl(solids):
    out = ["#VRML V2.0 utf8", "# generated by pcb/models3d.py; units 0.1 inch (KiCad's VRML convention)"]
    for kind, g, (r, gg, b) in solids:
        v, f = _mesh_box(g) if kind == "box" else _mesh_cyl(g)
        pts = ", ".join("%.4f %.4f %.4f" % (p[0] / U, p[1] / U, p[2] / U) for p in v)
        idx = ", ".join("%d, %d, %d, -1" % t for t in f)
        out.append("Shape { appearance Appearance { material Material { diffuseColor %.2f %.2f %.2f } } "
                   "geometry IndexedFaceSet { solid FALSE coord Coordinate { point [ %s ] } coordIndex [ %s ] } }" % (r, gg, b, pts, idx))
    return "\n".join(out) + "\n"


def write_all():
    os.makedirs(OUT, exist_ok=True)
    for name, solids in MODELS.items():
        open(os.path.join(OUT, name + ".wrl"), "w").write(wrl(solids))
    return sorted(MODELS)


if __name__ == "__main__":
    print("wrote", write_all())
